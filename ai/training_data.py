def build_dataset(seed: int = 42):
    """Return (texts, labels) after simple augmentation."""
    rng = random.Random(seed)
    texts, labels = [], []
    for category, langs in CATEGORIES.items():
        for lang, phrases in langs.items():
            for p in phrases:
                texts.append(p)
                labels.append(category)
                for _ in range(3):  # 3 augmented variants of each phrase
                    texts.append(rng.choice(OPENERS[lang]) + p + rng.choice(CLOSERS[lang]))
                    labels.append(category)
    return texts, labels
